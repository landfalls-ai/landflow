// Opt-in integration tests against real database servers: Postgres 16 (pgvector), Valkey 8
// (Redis protocol) and MySQL 8.4 from deploy/compose.infra.yml. They are skipped unless
// LANDFLOW_INTEGRATION names the service, so a plain `go test ./...` stays offline:
//
//	docker compose -f deploy/compose.infra.yml up -d --wait
//	LANDFLOW_INTEGRATION=postgres,redis go test -run Integration -v .
//
//	docker compose -f deploy/compose.infra.yml --profile mysql up -d --wait mysql
//	LANDFLOW_INTEGRATION=all go test -run Integration -v .
//
// Connections default to the infra stack's published ports and dev credentials; override them
// with LANDFLOW_IT_{PG,REDIS,MYSQL}_{HOST,PORT,USER,PASSWORD,DATABASE}. Each test works in its
// own schema, table or key prefix and removes it afterwards.

