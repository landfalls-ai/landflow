// integration skips the test unless LANDFLOW_INTEGRATION lists service (or is "all" / "1").
func integration(t *testing.T, service string) {
	t.Helper()
	enabled := strings.Split(strings.ToLower(os.Getenv("LANDFLOW_INTEGRATION")), ",")
	for _, s := range enabled {
		if s = strings.TrimSpace(s); s == service || s == "all" || s == "1" || s == "true" {
			return
		}
	}
	t.Skipf("set LANDFLOW_INTEGRATION=%s (or all) to run against a real server; see docs/deployment.md", service)
}

func itEnv(name, fallback string) string {
	if v := strings.TrimSpace(os.Getenv("LANDFLOW_IT_" + name)); v != "" {
		return v
	}
	return fallback
}

func itPort(name, fallback string) float64 {
	p, err := strconv.Atoi(itEnv(name, fallback))
	if err != nil {
		panic(fmt.Sprintf("LANDFLOW_IT_%s: %v", name, err))
	}
	return float64(p)
}

func suffix(t *testing.T) string {
	t.Helper()
	b := make([]byte, 4)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(b)
}

// sameInstant: v is an RFC 3339 timestamp for the same instant as want. Compare instants, not
// text, so the expectations can be written in any zone.
func sameInstant(v any, want string) bool {
	s, _ := v.(string)
	got, err1 := time.Parse(time.RFC3339Nano, s)
	exp, err2 := time.Parse(time.RFC3339Nano, want)
	return err1 == nil && err2 == nil && got.Equal(exp)
}

func execAll(t *testing.T, db *sql.DB, statements ...string) {
	t.Helper()
	for _, s := range statements {
		if _, err := db.Exec(s); err != nil {
			t.Fatalf("%s: %v", s, err)
		}
	}
}

