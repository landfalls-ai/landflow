func TestIntegrationMySQL(t *testing.T) {
	integration(t, "mysql")
	resetPools(t)
	data := landflow.CredentialData{
		"host":     itEnv("MYSQL_HOST", "127.0.0.1"),
		"port":     itPort("MYSQL_PORT", "53306"),
		"database": itEnv("MYSQL_DATABASE", "landflow_test"),
		"user":     itEnv("MYSQL_USER", "landflow"),
		"password": itEnv("MYSQL_PASSWORD", "landflow-dev-only"),
	}
	creds := map[string]any{"mySql": map[string]any(data)}
	db, err := openMySQL(data)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() }) // registered first, so it runs after the table is dropped
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		t.Fatalf("MySQL at %v:%v is not reachable (docker compose -f deploy/compose.infra.yml --profile mysql up -d --wait mysql): %v", data["host"], data["port"], err)
	}
	table := "it_products_" + suffix(t)
	execAll(t, db,
		"CREATE TABLE "+table+" (id INT PRIMARY KEY AUTO_INCREMENT, sku VARCHAR(20) UNIQUE, name VARCHAR(100), price DECIMAL(10,2), stock INT, added DATETIME, meta JSON)",
		"INSERT INTO "+table+" (sku, name, price, stock, added, meta) VALUES ('A-1', 'Anvil', 19.99, 3, '2026-01-02 03:04:05', '{\"vip\": true}'), ('B-2', 'Bolt', 0.25, 500, NULL, NULL)",
	)
	t.Cleanup(func() {
		pools.closeAll()
		if _, err := db.Exec("DROP TABLE IF EXISTS " + table); err != nil {
			t.Errorf("drop %s: %v", table, err)
		}
	})

	if ok, msg := mysqlCredential.Test(context.Background(), data); !ok {
		t.Fatalf("credential test = %v %q", ok, msg)
	}
	bad := landflow.CredentialData{}
	for k, v := range data {
		bad[k] = v
	}
	bad["password"] = "wrong-password"
	if ok, msg := mysqlCredential.Test(context.Background(), bad); ok || !strings.Contains(msg, "Access denied") || strings.Contains(msg, "wrong-password") {
		t.Errorf("bad password: ok=%v message=%q", ok, msg)
	}

	// Pickers.
	resp, err := newPlugin().LoadOptions(context.Background(), &landflow.LoadOptionsRequest{NodeType: "databases.mySql", Method: "getColumns",
		Parameters: map[string]any{"table": table}, Credentials: creds})
	if err != nil || len(resp.Options) != 7 || resp.Options[1].Value != "sku" {
		t.Fatalf("columns = %+v %v", resp, err)
	}

	// Select with conversions: DECIMAL as string, DATETIME as RFC 3339, JSON parsed.
	rows := ok(t, call{node: "mySql", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "select", "table": table, "where": where([3]any{"price", ">", "1"})}})
	if len(rows) != 1 || rows[0].JSON["name"] != "Anvil" || rows[0].JSON["price"] != "19.99" || rows[0].JSON["added"] != "2026-01-02T03:04:05Z" || num(rows[0].JSON["stock"]) != 3 {
		t.Errorf("select = %+v", rows)
	}
	if meta, _ := rows[0].JSON["meta"].(map[string]any); meta == nil || meta["vip"] != true {
		t.Errorf("json = %#v", rows[0].JSON["meta"])
	}

	// Insert, upsert (ON DUPLICATE KEY UPDATE), update, delete guard and delete.
	rows = ok(t, call{node: "mySql", creds: creds, params: map[string]any{"operation": "insert", "table": table},
		items: []map[string]any{{"sku": "C-3", "name": "Cog", "price": 2.5, "stock": 10.0, "colour": "ignored"}}})
	if len(rows) != 1 || rows[0].JSON["sku"] != "C-3" {
		t.Errorf("insert = %+v", rows)
	}
	ok(t, call{node: "mySql", creds: creds, params: map[string]any{"operation": "upsert", "table": table, "columnsToMatchOn": "sku"},
		items: []map[string]any{{"sku": "A-1", "name": "Anvil XL", "stock": 4.0}, {"sku": "D-4", "name": "Drill", "stock": 1.0}}})
	rows = ok(t, call{node: "mySql", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "executeQuery", "query": "SELECT sku, name, stock FROM " + table + " WHERE sku IN (?, ?) ORDER BY sku",
		"options": map[string]any{"queryReplacement": "A-1, D-4"}}})
	if len(rows) != 2 || rows[0].JSON["name"] != "Anvil XL" || num(rows[0].JSON["stock"]) != 4 || rows[1].JSON["name"] != "Drill" {
		t.Errorf("after upsert = %+v", rows)
	}
	rows = ok(t, call{node: "mySql", creds: creds, params: map[string]any{"operation": "update", "table": table, "columnToMatchOn": "sku"},
		items: []map[string]any{{"sku": "B-2", "stock": 499.0}}})
	if num(rows[0].JSON["affectedRows"]) != 1 {
		t.Errorf("update = %+v", rows)
	}
	e := fails(t, call{node: "mySql", creds: creds, items: []map[string]any{{}}, params: map[string]any{"operation": "deleteTable", "table": table}})
	if !strings.Contains(e.Message, "Refusing") {
		t.Errorf("delete guard = %+v", e)
	}
	rows = ok(t, call{node: "mySql", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "deleteTable", "table": table, "where": where([3]any{"stock", "<", "2"})}})
	if num(rows[0].JSON["affectedRows"]) != 1 {
		t.Errorf("delete = %+v", rows)
	}

	// The server's own error reaches the node error.
	e = fails(t, call{node: "mySql", creds: creds, items: []map[string]any{{}}, params: map[string]any{"operation": "executeQuery", "query": "SELECT * FROM it_missing_table"}})
	if !strings.Contains(e.Message, "it_missing_table") {
		t.Errorf("server error = %+v", e)
	}
}
