func pgIntegration(t *testing.T) (map[string]any, landflow.CredentialData, *sql.DB, string) {
	t.Helper()
	integration(t, "postgres")
	resetPools(t)
	data := landflow.CredentialData{
		"host":     itEnv("PG_HOST", "127.0.0.1"),
		"port":     itPort("PG_PORT", "55432"),
		"database": itEnv("PG_DATABASE", "landflow_test"),
		"user":     itEnv("PG_USER", "landflow"),
		"password": itEnv("PG_PASSWORD", "landflow-dev-only"),
		"ssl":      "disable",
	}
	db, err := openPostgres(data)
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		t.Fatalf("Postgres at %v:%v is not reachable (docker compose -f deploy/compose.infra.yml up -d --wait): %v", data["host"], data["port"], err)
	}
	schema := "it_" + suffix(t)
	execAll(t, db, `CREATE SCHEMA `+schema)
	t.Cleanup(func() {
		pools.closeAll()
		if _, err := db.Exec(`DROP SCHEMA ` + schema + ` CASCADE`); err != nil {
			t.Errorf("drop schema %s: %v", schema, err)
		}
		db.Close()
	})
	return map[string]any{"postgres": map[string]any(data)}, data, db, schema
}

func TestIntegrationPostgresNode(t *testing.T) {
	creds, data, db, schema := pgIntegration(t)
	execAll(t, db,
		`CREATE EXTENSION IF NOT EXISTS vector`,
		`CREATE TABLE `+schema+`.products (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			sku text UNIQUE NOT NULL,
			name text,
			price numeric(10,2),
			in_stock boolean,
			meta jsonb,
			added timestamptz,
			embedding vector(3)
		)`,
	)

	if ok, msg := postgresCredential.Test(context.Background(), data); !ok {
		t.Fatalf("credential test = %v %q", ok, msg)
	}
	bad := landflow.CredentialData{}
	for k, v := range data {
		bad[k] = v
	}
	bad["password"] = "wrong-password"
	if ok, msg := postgresCredential.Test(context.Background(), bad); ok || !strings.Contains(msg, "password authentication failed") || strings.Contains(msg, "wrong-password") {
		t.Errorf("bad password: ok=%v message=%q", ok, msg)
	}

	// Pickers read the real catalogue.
	load := func(method string, params map[string]any) []string {
		resp, err := newPlugin().LoadOptions(context.Background(), &landflow.LoadOptionsRequest{NodeType: "databases.postgres", Method: method, Parameters: params, Credentials: creds})
		if err != nil {
			t.Fatalf("%s: %v", method, err)
		}
		var values []string
		for _, o := range resp.Options {
			values = append(values, fmt.Sprint(o.Value))
		}
		return values
	}
	if s := load("getSchemas", nil); !slices.Contains(s, schema) {
		t.Errorf("schemas %v lack %s", s, schema)
	}
	if tb := load("getTables", map[string]any{"schema": schema}); !slices.Equal(tb, []string{"products"}) {
		t.Errorf("tables = %v", tb)
	}
	if c := load("getColumns", map[string]any{"schema": schema, "table": "products"}); len(c) != 8 || c[1] != "sku" || c[7] != "embedding" {
		t.Errorf("columns = %v", c)
	}

	// Insert (automatic mapping, server-side type conversion, RETURNING *): numeric, boolean,
	// jsonb from an object, timestamptz from RFC 3339 text and a pgvector value from text.
	rows := ok(t, call{node: "postgres", creds: creds, params: map[string]any{"operation": "insert", "schema": schema, "table": "products"},
		items: []map[string]any{
			{"sku": "A-1", "name": "Anvil", "price": 19.99, "in_stock": true, "meta": map[string]any{"tags": []any{"heavy"}}, "added": "2026-01-02T03:04:05Z", "embedding": "[1,2,3]", "ignored": "x"},
			{"sku": "B-2", "name": "Bolt", "price": 0.25, "in_stock": false, "embedding": "[0,0,1]"},
		}})
	if len(rows) != 2 || rows[0].JSON["sku"] != "A-1" || rows[0].JSON["price"] != "19.99" || rows[0].JSON["in_stock"] != true ||
		!sameInstant(rows[0].JSON["added"], "2026-01-02T03:04:05Z") || rows[0].JSON["embedding"] != "[1,2,3]" {
		t.Fatalf("insert = %+v", rows)
	}
	if meta, _ := rows[0].JSON["meta"].(map[string]any); meta == nil || fmt.Sprint(meta["tags"]) != "[heavy]" {
		t.Errorf("jsonb = %#v", rows[0].JSON["meta"])
	}

	// Select: conditions, sort, limit, output columns.
	rows = ok(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "select", "schema": schema, "table": "products", "limit": 1.0,
		"where":   where([3]any{"price", ">=", "0.1"}, [3]any{"meta", "IS NULL", ""}),
		"sort":    map[string]any{"values": []any{map[string]any{"column": "sku", "direction": "DESC"}}},
		"options": map[string]any{"outputColumns": "sku,price,in_stock"},
	}})
	if len(rows) != 1 || rows[0].JSON["sku"] != "B-2" || rows[0].JSON["price"] != "0.25" || rows[0].JSON["in_stock"] != false || len(rows[0].JSON) != 3 {
		t.Errorf("select = %+v", rows)
	}

	// Insert or Update on the unique sku: one update, one insert.
	ok(t, call{node: "postgres", creds: creds, params: map[string]any{"operation": "upsert", "schema": schema, "table": "products", "columnsToMatchOn": "sku"},
		items: []map[string]any{{"sku": "A-1", "name": "Anvil XL", "price": 24.5}, {"sku": "C-3", "name": "Cog", "price": 2.0}}})
	// Update by a column, returning the rows.
	rows = ok(t, call{node: "postgres", creds: creds, params: map[string]any{"operation": "update", "schema": schema, "table": "products", "columnToMatchOn": "sku"},
		items: []map[string]any{{"sku": "B-2", "in_stock": true}}})
	if len(rows) != 1 || rows[0].JSON["in_stock"] != true || rows[0].JSON["name"] != "Bolt" {
		t.Errorf("update = %+v", rows)
	}

	// Execute Query with bound parameters, and pgvector distance in SQL.
	rows = ok(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "executeQuery",
		"query":     "SELECT sku, name, price, embedding <-> $1::vector AS distance FROM " + schema + ".products WHERE sku = ANY(string_to_array($2, ',')) ORDER BY sku",
		"options":   map[string]any{"queryReplacement": `"[1,2,3]", "A-1,C-3"`},
	}})
	if len(rows) != 2 || rows[0].JSON["name"] != "Anvil XL" || rows[0].JSON["price"] != "24.50" || num(rows[0].JSON["distance"]) != 0 || rows[1].JSON["sku"] != "C-3" {
		t.Errorf("execute query = %+v", rows)
	}

	// Conversions the mocks can't prove: BIGINT beyond 2^53 and BYTEA.
	rows = ok(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "executeQuery", "query": "SELECT 9007199254740993::bigint AS big, 42::int8 AS small, decode('01020304', 'hex') AS raw, 1.5::float8 AS f",
	}})
	if len(rows) != 1 || rows[0].JSON["big"] != "9007199254740993" || num(rows[0].JSON["small"]) != 42 || rows[0].JSON["raw"] != "AQIDBA==" || num(rows[0].JSON["f"]) != 1.5 {
		t.Errorf("conversions = %+v", rows)
	}

	// Transaction batching: the second item violates the unique key, so the first rolls back too,
	// and the node error carries the server's message.
	insert := "INSERT INTO " + schema + ".products (sku, name) VALUES ($1, $2)"
	opts := func(p string) map[string]any {
		return map[string]any{"operation": "executeQuery", "query": insert, "options": map[string]any{"queryReplacement": p, "queryBatching": "transaction"}}
	}
	e := fails(t, call{node: "postgres", creds: creds, params: opts("T-1, one"),
		items: []map[string]any{{}, {}}, itemParams: []map[string]any{opts("T-1, one"), opts("A-1, duplicate")}})
	if !strings.Contains(e.Message, "duplicate key") {
		t.Errorf("transaction error = %+v", e)
	}
	var n int
	if err := db.QueryRow(`SELECT count(*) FROM ` + schema + `.products WHERE sku = 'T-1'`).Scan(&n); err != nil || n != 0 {
		t.Errorf("rolled back row count = %d (%v)", n, err)
	}

	// Delete: refused without conditions, then by condition.
	e = fails(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{"operation": "deleteTable", "schema": schema, "table": "products"}})
	if !strings.Contains(e.Message, "Refusing") {
		t.Errorf("delete guard = %+v", e)
	}
	rows = ok(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "deleteTable", "schema": schema, "table": "products", "where": where([3]any{"sku", "equal", "C-3"})}})
	if len(rows) != 1 || num(rows[0].JSON["affectedRows"]) != 1 {
		t.Errorf("delete = %+v", rows)
	}
	if err := db.QueryRow(`SELECT count(*) FROM ` + schema + `.products`).Scan(&n); err != nil || n != 2 {
		t.Errorf("rows left = %d (%v)", n, err)
	}

	// Identifiers are checked against the catalogue, not interpolated.
	e = fails(t, call{node: "postgres", creds: creds, items: []map[string]any{{}}, params: map[string]any{
		"operation": "select", "schema": schema, "table": `products"; DROP TABLE x; --`}})
	if !strings.Contains(e.Message, "does not exist") {
		t.Errorf("bad table = %+v", e)
	}
}

func TestIntegrationPostgresTrigger(t *testing.T) {
	creds, _, db, schema := pgIntegration(t)
	execAll(t, db,
		`CREATE TABLE `+schema+`.events (id bigserial PRIMARY KEY, kind text NOT NULL, at timestamptz DEFAULT now())`,
		`INSERT INTO `+schema+`.events (kind) VALUES ('old-1'), ('old-2')`,
	)
	params := map[string]any{"schema": schema, "table": "events", "trackingColumn": "id", "limit": 10.0}

	// First poll: baseline only.
	resp := execute(t, call{node: "postgresTrigger", creds: creds, params: params, mode: landflow.ModePoll})
	if resp.Error != nil || len(resp.Outputs) == 0 || len(resp.Outputs[0]) != 0 || resp.PollState["lastValue"] != "2" {
		t.Fatalf("baseline = %+v", resp)
	}
	// Nothing new.
	resp = execute(t, call{node: "postgresTrigger", creds: creds, params: params, mode: landflow.ModePoll, state: resp.PollState})
	if resp.Error != nil || len(resp.Outputs[0]) != 0 {
		t.Fatalf("idle poll = %+v", resp)
	}
	state := map[string]any{"lastValue": "2"}

	execAll(t, db, `INSERT INTO `+schema+`.events (kind) VALUES ('new-1'), ('new-2'), ('new-3')`)
	resp = execute(t, call{node: "postgresTrigger", creds: creds, params: params, mode: landflow.ModePoll, state: state})
	if resp.Error != nil || len(resp.Outputs[0]) != 3 || resp.PollState["lastValue"] != "5" {
		t.Fatalf("poll = %+v", resp)
	}
	first := resp.Outputs[0][0].JSON
	if first["kind"] != "new-1" || num(first["id"]) != 3 {
		t.Errorf("first new row = %+v", first)
	}
	if _, leaked := first[cursorAlias]; leaked {
		t.Errorf("cursor column leaked: %+v", first)
	}
	if at, err := time.Parse(time.RFC3339Nano, fmt.Sprint(first["at"])); err != nil || time.Since(at) > time.Hour || time.Since(at) < -time.Hour {
		t.Errorf("timestamptz = %#v (%v)", first["at"], err)
	}

	// Manual run: the latest five, oldest first, state untouched.
	resp = execute(t, call{node: "postgresTrigger", creds: creds, params: params, mode: landflow.ModeManual})
	if resp.Error != nil || resp.PollState != nil || len(resp.Outputs[0]) != 5 || num(resp.Outputs[0][0].JSON["id"]) != 1 || num(resp.Outputs[0][4].JSON["id"]) != 5 {
		t.Errorf("manual = %+v", resp)
	}
}

