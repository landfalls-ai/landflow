func TestIntegrationRedis(t *testing.T) {
	integration(t, "redis")
	resetPools(t)
	host, port := itEnv("REDIS_HOST", "127.0.0.1"), itPort("REDIS_PORT", "56379")
	data := landflow.CredentialData{"host": host, "port": port, "database": 0.0}
	if pw := itEnv("REDIS_PASSWORD", ""); pw != "" {
		data["password"] = pw
	}
	creds := map[string]any{"redis": map[string]any(data)}
	rc := redis.NewClient(&redis.Options{Addr: fmt.Sprintf("%s:%d", host, int(port)), Password: itEnv("REDIS_PASSWORD", "")})
	ctx := context.Background()
	if err := rc.Ping(ctx).Err(); err != nil {
		t.Fatalf("Redis/Valkey at %s:%d is not reachable (docker compose -f deploy/compose.infra.yml up -d --wait): %v", host, int(port), err)
	}
	prefix := "it" + suffix(t)
	t.Cleanup(func() {
		pools.closeAll()
		keys, _ := rc.Keys(ctx, prefix+":*").Result()
		if len(keys) > 0 {
			rc.Del(ctx, keys...)
		}
		rc.Close()
	})
	k := func(name string) string { return prefix + ":" + name }

	if ok, msg := redisCredential.Test(ctx, data); !ok {
		t.Fatalf("credential test = %v %q", ok, msg)
	}
	closed := landflow.CredentialData{"host": host, "port": 1.0, "database": 0.0}
	if ok, msg := redisCredential.Test(ctx, closed); ok || msg == "" {
		t.Errorf("closed port: ok=%v message=%q", ok, msg)
	}

	// Set: string with expiry, object as hash, array as list.
	ok(t, redisCall(creds, map[string]any{"operation": "set", "key": k("greeting"), "value": "hello", "expire": true, "ttl": 60.0}))
	ok(t, redisCall(creds, map[string]any{"operation": "set", "key": k("user"), "value": map[string]any{"name": "Ada", "age": 36.0}}))
	ok(t, redisCall(creds, map[string]any{"operation": "set", "key": k("queue"), "value": []any{"a", "b"}}))
	if ttl := rc.TTL(ctx, k("greeting")).Val(); ttl <= 0 || ttl > 60*time.Second {
		t.Errorf("ttl = %v", ttl)
	}
	if rc.HGet(ctx, k("user"), "name").Val() != "Ada" || rc.Type(ctx, k("queue")).Val() != "list" {
		t.Error("hash / list not stored as such")
	}

	// Get with automatic types.
	get := func(key string) any {
		out := ok(t, redisCall(creds, map[string]any{"operation": "get", "key": key, "propertyName": "value"}))
		return out[0].JSON["value"]
	}
	if v := get(k("greeting")); v != "hello" {
		t.Errorf("get string = %#v", v)
	}
	if v, _ := get(k("user")).(map[string]any); v["name"] != "Ada" {
		t.Errorf("get hash = %#v", v)
	}
	if v := get(k("missing")); v != nil {
		t.Errorf("get missing = %#v", v)
	}

	// Increment, push / pop, length.
	ok(t, redisCall(creds, map[string]any{"operation": "incr", "key": k("hits")}))
	out := ok(t, redisCall(creds, map[string]any{"operation": "incr", "key": k("hits")}))
	if num(out[0].JSON[k("hits")]) != 2 {
		t.Errorf("incr = %+v", out)
	}
	ok(t, redisCall(creds, map[string]any{"operation": "push", "list": k("jobs"), "messageData": `{"id":1}`, "tail": true}))
	ok(t, redisCall(creds, map[string]any{"operation": "push", "list": k("jobs"), "messageData": "second", "tail": true}))
	out = ok(t, redisCall(creds, map[string]any{"operation": "llen", "list": k("jobs")}))
	if num(out[0].JSON["length"]) != 2 {
		t.Errorf("llen = %+v", out)
	}
	out = ok(t, redisCall(creds, map[string]any{"operation": "pop", "list": k("jobs"), "propertyName": "job"}))
	if job, _ := out[0].JSON["job"].(map[string]any); num(job["id"]) != 1 {
		t.Errorf("pop = %+v", out)
	}

	// Keys (SCAN) with values, sorted.
	out = ok(t, redisCall(creds, map[string]any{"operation": "keys", "keyPattern": prefix + ":*", "returnAll": true, "getValues": false}))
	keys, _ := out[0].JSON["keys"].([]any)
	if len(keys) != 5 || keys[0] != k("greeting") {
		t.Errorf("keys = %+v", out)
	}

	// Info parses the real server's sections; Publish reaches a subscriber.
	out = ok(t, redisCall(creds, map[string]any{"operation": "info"}))
	if out[0].JSON["redis_version"] == nil && out[0].JSON["valkey_version"] == nil {
		t.Errorf("info has no server version: %v", out[0].JSON)
	}
	sub := rc.Subscribe(ctx, k("events"))
	defer sub.Close()
	if _, err := sub.Receive(ctx); err != nil {
		t.Fatal(err)
	}
	ok(t, redisCall(creds, map[string]any{"operation": "publish", "channel": k("events"), "messageData": "ping"}))
	select {
	case msg := <-sub.Channel():
		if msg.Payload != "ping" {
			t.Errorf("published %q", msg.Payload)
		}
	case <-time.After(3 * time.Second):
		t.Error("no message on the channel")
	}

	ok(t, redisCall(creds, map[string]any{"operation": "delete", "key": k("greeting")}))
	if rc.Exists(ctx, k("greeting")).Val() != 0 {
		t.Error("delete left the key")
	}
}

