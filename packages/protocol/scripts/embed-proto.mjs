// Embeds plugin.proto into src/generated/plugin-proto.ts so bundlers never
// have to locate the .proto file at runtime.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const proto = readFileSync(join(root, 'proto/landflow/plugin/v1/plugin.proto'), 'utf8');
const out = join(root, 'src/generated/plugin-proto.ts');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// GENERATED by scripts/embed-proto.mjs from proto/landflow/plugin/v1/plugin.proto — do not edit.\n` +
    `export const PLUGIN_PROTO = ${JSON.stringify(proto)};\n`,
);
console.log(`wrote ${out}`);
